package main

// P3-7 — the P3 completion audit: testdata/realworld is a nested Go
// module holding seven small-but-real package-main programs that drive
// the Go interop surface end to end — file IO (os/io/bufio), argv
// and strconv with |?> wrapping, flag + an extern override, a JSON
// round-trip through the streaming Encoder/Decoder API, CSV→JSON, date arithmetic/time,
// and an HTTP client. This driver copies the fixture, runs the real
// gom CLI through check and build, compiles each program with the
// Go toolchain, and executes the binaries asserting their output —
// including an httptest server for httpfetch.

import (
	"fmt"
	"github.com/podhmo/gom/internal/testbin"
	"net/http"
	"net/http/httptest"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// copyRealworld copies the testdata/realworld tree into dir,
// skipping a .go file only when a same-basename .gom sibling exists —
// those are `gom build` output regenerated during the test.
func copyRealworld(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if info.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		if strings.HasSuffix(path, ".go") {
			if _, err := os.Stat(strings.TrimSuffix(path, ".go") + ".gom"); err == nil {
				return nil // generated by `gom build` during the test
			}
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

// runBin executes a compiled fixture binary inside dir (the
// fixture's data/ paths are module-relative), returning exit code,
// stdout, and stderr without failing the test — the fixture's error
// paths are asserted as part of the audit.
func runBin(t *testing.T, bin, dir, stdin string, args ...string) (int, string, string) {
	t.Helper()
	cmd := testbin.Command(bin, args...)
	cmd.Dir = dir
	if stdin != "" {
		cmd.Stdin = strings.NewReader(stdin)
	}
	var out, errout strings.Builder
	cmd.Stdout, cmd.Stderr = &out, &errout
	err := cmd.Run()
	code := 0
	if err != nil {
		exit, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatalf("run %s %v: %v", bin, args, err)
		}
		code = exit.ExitCode()
	}
	return code, out.String(), errout.String()
}

func TestEndToEnd_RealWorldPrograms(t *testing.T) {
	if testing.Short() {
		t.Skipf("long test: %.2fs on last run, skipping in short mode", 13.37)
	}

	gobin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("no go toolchain on PATH")
	}
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	copyRealworld(t, filepath.Join(root, "testdata", "realworld"), dir)
	if !goAtLeast(gobin, dir, 1, 27) {
		t.Skip("fixture requires go >= 1.27 (testdata/realworld/go.mod)")
	}

	// Point the committed relative replace at this worktree.
	gomodPath := filepath.Join(dir, "go.mod")
	gomod, err := os.ReadFile(gomodPath)
	if err != nil {
		t.Fatal(err)
	}
	gomod = []byte(strings.ReplaceAll(string(gomod), "=> ../..", "=> "+root))
	if err := os.WriteFile(gomodPath, gomod, 0o644); err != nil {
		t.Fatal(err)
	}

	progs := []string{"wc", "cal", "greet", "jsoncfg", "csvtojson", "httpfetch", "datemath", "errwalk"}
	dirs := make([]string, len(progs))
	for i, p := range progs {
		dirs[i] = filepath.Join(dir, p)
	}

	// gom check the whole fixture at once: every program compiles as
	// its own package-main unit.
	args := append([]string{"check", "-format", "text"}, dirs...)
	if code, out, errout := invoke(args...); code != 0 {
		t.Fatalf("gom check: exit %d; stdout=%q stderr=%q", code, out, errout)
	}

	// gom build emits one .go next to each .gom.
	args = append([]string{"build"}, dirs...)
	if code, out, errout := invoke(args...); code != 0 {
		t.Fatalf("gom build: exit %d; stdout=%q stderr=%q", code, out, errout)
	}
	for _, p := range progs {
		if _, err := os.Stat(filepath.Join(dir, p, "main.go")); err != nil {
			t.Fatalf("expected generated file %s/main.go: %v", p, err)
		}
	}

	// The Go toolchain compiles every generated program.
	goCmd(t, gobin, dir, "build", "./...")

	bin := filepath.Join(dir, "bin")
	buildOne := func(pkg string) string {
		t.Helper()
		out := filepath.Join(bin, pkg)
		goCmd(t, gobin, dir, "build", "-o", out, "./"+pkg)
		return out
	}

	// wc: lines + bytes per file from committed data, `-` for stdin,
	// missing files reported through errors.Is(os.ErrNotExist).
	wcBin := buildOne("wc")
	if code, out, errout := runBin(t, wcBin, dir, "",
		"data/notes.txt", "data/lorem.txt"); code != 0 ||
		out != "3\t34\tdata/notes.txt\n2\t31\tdata/lorem.txt\n" || errout != "" {
		t.Fatalf("wc files: code=%d out=%q err=%q", code, out, errout)
	}
	if code, out, errout := runBin(t, wcBin, dir, "x\ny\n", "-"); code != 0 ||
		out != "2\t4\t-\n" || errout != "" {
		t.Fatalf("wc stdin: code=%d out=%q err=%q", code, out, errout)
	}
	if code, out, errout := runBin(t, wcBin, dir, "",
		"data/notes.txt", "data/missing.txt"); code != 1 ||
		out != "3\t34\tdata/notes.txt\n" ||
		errout != "wc: data/missing.txt: no such file\n" {
		t.Fatalf("wc missing: code=%d out=%q err=%q", code, out, errout)
	}

	// cal: argv List + strconv, |?> step-name wrapping on failure.
	calBin := buildOne("cal")
	for _, tc := range []struct {
		args []string
		want string
	}{
		{[]string{"add", "1", "2", "3"}, "6\n"},
		{[]string{"mul", "4", "5"}, "20\n"},
		{[]string{"max", "3", "9", "2"}, "9\n"},
	} {
		if code, out, errout := runBin(t, calBin, dir, "", tc.args...); code != 0 || out != tc.want {
			t.Fatalf("cal %v: code=%d out=%q err=%q want %q", tc.args, code, out, errout, tc.want)
		}
	}
	if code, out, errout := runBin(t, calBin, dir, "", "add", "1", "x"); code != 1 ||
		out != "" || !strings.Contains(errout, "cal/main.gom:") ||
		!strings.Contains(errout, `strconv.Atoi: parsing "x": invalid syntax`) {
		t.Fatalf("cal bad int: code=%d out=%q err=%q", code, out, errout)
	}
	if code, out, errout := runBin(t, calBin, dir, "", "bogus", "1"); code != 1 ||
		out != "" || !strings.Contains(errout, "unknown op: bogus") {
		t.Fatalf("cal bad op: code=%d out=%q err=%q", code, out, errout)
	}
	if code, _, _ := runBin(t, calBin, dir, ""); code != 2 {
		t.Fatalf("cal usage: code=%d, want 2", code)
	}

	// greet: flag.Bool/Int64 + flag.Args; flag values through extern
	// flag.Lookup -> Option (Ptr Flag) -> Value.String.
	greetBin := buildOne("greet")
	if code, out, _ := runBin(t, greetBin, dir, ""); code != 0 || out != "hello, world\n" {
		t.Fatalf("greet default: code=%d out=%q", code, out)
	}
	if code, out, _ := runBin(t, greetBin, dir, "",
		"-shout", "-times", "2", "ann", "bob"); code != 0 ||
		out != "HELLO, ann\nHELLO, ann\nHELLO, bob\nHELLO, bob\n" {
		t.Fatalf("greet flags: code=%d out=%q", code, out)
	}

	// jsoncfg: record -> json.Encoder -> text, then a flat-object
	// parse through Decoder.Token/%v renderings — the round-trip
	// must reproduce the record.
	jsoncfgBin := buildOne("jsoncfg")
	if code, out, errout := runBin(t, jsoncfgBin, dir, ""); code != 0 ||
		!strings.HasPrefix(out, "{\n") || !strings.HasSuffix(out, "round-trip ok\n") ||
		!strings.Contains(out, `"Name": "gom"`) || errout != "" {
		t.Fatalf("jsoncfg: code=%d out=%q err=%q", code, out, errout)
	}

	// csvtojson: CSV file -> one JSON array per row.
	csvtojsonBin := buildOne("csvtojson")
	wantCSV := "[\"name\",\"city\"]\n[\"ann\",\"paris\"]\n[\"bob\",\"lyon\"]\n"
	if code, out, errout := runBin(t, csvtojsonBin, dir, "", "data/people.csv"); code != 0 ||
		out != wantCSV || errout != "" {
		t.Fatalf("csvtojson: code=%d out=%q err=%q", code, out, errout)
	}

	// datemath: time.Parse + AddDate + Weekday on named Go values.
	datemathBin := buildOne("datemath")
	if code, out, errout := runBin(t, datemathBin, dir, "", "2024-02-28", "2"); code != 0 ||
		out != "2024-03-01 (Friday)\n" || errout != "" {
		t.Fatalf("datemath: code=%d out=%q err=%q", code, out, errout)
	}
	if code, _, errout := runBin(t, datemathBin, dir, "", "2024-02-30", "1"); code != 1 ||
		!strings.Contains(errout, "day out of range") {
		t.Fatalf("datemath bad date: code=%d err=%q", code, errout)
	}

	// httpfetch: a real GET against a loopback httptest server —
	// http.DefaultClient, response field reads, io.Copy of the body.
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Accept") != "text/plain" {
			t.Errorf("Accept header = %q, want text/plain", r.Header.Get("Accept"))
		}
		fmt.Fprintln(w, "hello over http")
	}))
	defer srv.Close()
	httpfetchBin := buildOne("httpfetch")
	if code, out, errout := runBin(t, httpfetchBin, dir, "", srv.URL); code != 0 ||
		out != "status: 200\nhello over http\n(16 bytes shown)\n" || errout != "" {
		t.Fatalf("httpfetch: code=%d out=%q err=%q", code, out, errout)
	}
	// A closed loopback listener refuses connections deterministically
	// (unroutable addresses can hang under network sandboxes).
	dead := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {}))
	deadURL := dead.URL
	dead.Close()
	if code, _, errout := runBin(t, httpfetchBin, dir, "", deadURL); code != 1 ||
		!strings.Contains(errout, "httpfetch:") {
		t.Fatalf("httpfetch refused: code=%d err=%q", code, errout)
	}

	// errwalk: the GoError value surface — the standard bindings'
	// declared views plus Is/As/Unwrap/Join over a *strconv.NumError.
	errwalkBin := buildOne("errwalk")
	wantWalk := "is-syntax: true\nwrapped-is: true\n" +
		"as-numerr: true\nas-func: Atoi\n" +
		"unwrap-is: true\nbase-unwrap-is: true\nleaf-unwrap: none\n" +
		"join-is: true\n" +
		"join-text: strconv.Atoi: parsing \"x\": invalid syntax\nextra\n" +
		"pipe-text: strconv.Atoi: strconv.Atoi: parsing \"x\": invalid syntax\n" +
		"frame-as: true\nframe-step: strconv.Atoi\n"
	if code, out, errout := runBin(t, errwalkBin, dir, ""); code != 0 ||
		out != wantWalk || errout != "" {
		t.Fatalf("errwalk: code=%d out=%q err=%q\nwant %q", code, out, errout, wantWalk)
	}
	// The `panic` path: `os.Remove` succeeds and returns nil, but the
	// file's extern claims `-> GoError` — the boundary check panics
	// rather than handing back a nil error value.
	if code, _, errout := runBin(t, errwalkBin, dir, "", "panic"); code != 2 ||
		!strings.Contains(errout, "declares a never-nil GoError result") {
		t.Fatalf("errwalk panic: code=%d err=%q", code, errout)
	}
	// The `pair` path: the derived `(error, error)` view reads the
	// nil-able payload as `Option GoError` — `(nil, nil)` is `Ok
	// None`, a soft error `Ok (Some e)`, a fatal one `Err e` — and
	// `|?>`/`try` apply the same `option.FromGo` read.
	wantPair := "pair-0: none\npair-1: some soft\npair-neg: err fatal\n" +
		"pipe-pair: some soft\ntry-opt: none\n"
	if code, out, errout := runBin(t, errwalkBin, dir, "", "pair"); code != 0 ||
		out != wantPair || errout != "" {
		t.Fatalf("errwalk pair: code=%d out=%q err=%q\nwant %q", code, out, errout, wantPair)
	}
	// `trypair`/`pipepair`: the declared `Result GoError GoError`
	// claims a never-nil payload — `(nil, nil)` violates it and the
	// boundary panics, in the plain try and the fused |?> step
	// alike.
	if code, _, errout := runBin(t, errwalkBin, dir, "", "trypair"); code != 2 ||
		!strings.Contains(errout, "declares a never-nil GoError payload") {
		t.Fatalf("errwalk trypair: code=%d err=%q", code, errout)
	}
	if code, _, errout := runBin(t, errwalkBin, dir, "", "pipepair"); code != 2 ||
		!strings.Contains(errout, "declares a never-nil GoError payload") {
		t.Fatalf("errwalk pipepair: code=%d err=%q", code, errout)
	}
}

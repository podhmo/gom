package main

// Multi-file vertical slice (task V-6): testdata/multifile is a
// nested Go module holding a library of two .gom files plus one
// .gomi, a Gom consumer package, and a Go consumer test. This test
// copies the fixture, runs the real gom CLI through check and build,
// then lets the real Go toolchain compile the generated package and
// run both consumers end to end.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// copyFixture copies the testdata/multifile tree into dir, skipping
// generated *.go siblings of .gom files so a stale local build can
// never leak into the test.
func copyFixture(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if info.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		dir := filepath.Base(filepath.Dir(path))
		if strings.HasSuffix(path, ".go") && (dir == "shapes" || dir == "gomapp") {
			return nil // generated by `gom build` during the test
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

func goCmd(t *testing.T, gobin, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command(gobin, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOTOOLCHAIN=local")
	b, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s in %s: %v\n%s", strings.Join(args, " "), dir, err, b)
	}
	return string(b)
}

// goAtLeast reports whether the go toolchain resolves to at least
// the given version inside dir — run inside the module so
// GOTOOLCHAIN's auto-switch reports the toolchain that would
// actually build it (the fixture module declares `go 1.27`).
func goAtLeast(gobin, dir string, major, minor int) bool {
	cmd := exec.Command(gobin, "version")
	cmd.Dir = dir
	out, err := cmd.Output()
	if err != nil {
		return false
	}
	var maj, min int
	if _, err := fmt.Sscanf(string(out), "go version go%d.%d", &maj, &min); err != nil {
		return false
	}
	return maj > major || (maj == major && min >= minor)
}

func TestEndToEnd_MultifilePackage(t *testing.T) {
	if testing.Short() {
		t.Skipf("long test: %.2fs on last run, skipping in short mode", 3.99)
	}

	t.Parallel()

	gobin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("no go toolchain on PATH")
	}
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	copyFixture(t, filepath.Join(root, "testdata", "multifile"), dir)
	if !goAtLeast(gobin, dir, 1, 27) {
		t.Skip("fixture requires go >= 1.27 (testdata/multifile/go.mod)")
	}

	// The committed go.mod uses a relative replace so the fixture is
	// readable; point it at this worktree in the temp copy.
	gomodPath := filepath.Join(dir, "go.mod")
	gomod, err := os.ReadFile(gomodPath)
	if err != nil {
		t.Fatal(err)
	}
	gomod = []byte(strings.ReplaceAll(string(gomod), "=> ../..", "=> "+root))
	if err := os.WriteFile(gomodPath, gomod, 0o644); err != nil {
		t.Fatal(err)
	}

	shapesDir := filepath.Join(dir, "shapes")
	gomappDir := filepath.Join(dir, "gomapp")

	// gom check on both directories at once: shapes compiles as one
	// unit (two files sharing package scope), gomapp resolves the
	// library through its .gomi.
	if code, out, errout := invoke("check", "-format", "text", shapesDir, gomappDir); code != 0 {
		t.Fatalf("gom check: exit %d; stdout=%q stderr=%q", code, out, errout)
	}

	// gom build emits shapes/shapes.go + shapes/ops.go (same package)
	// and gomapp/main.go importing the generated library package.
	if code, out, errout := invoke("build", shapesDir, gomappDir); code != 0 {
		t.Fatalf("gom build: exit %d; stdout=%q stderr=%q", code, out, errout)
	}
	for _, rel := range []string{
		"shapes/shapes.go", "shapes/ops.go", "gomapp/main.go",
	} {
		if _, err := os.Stat(filepath.Join(dir, rel)); err != nil {
			t.Fatalf("expected generated file %s: %v", rel, err)
		}
	}

	// The Go toolchain compiles the whole module: generated library,
	// generated Gom consumer, and the hand-written Go consumer test.
	goCmd(t, gobin, dir, "build", "./...")
	if out := goCmd(t, gobin, dir, "test", "./..."); !strings.Contains(out, "ok  \texample.com/multifile/app") && !strings.Contains(out, "ok  	example.com/multifile/app") {
		t.Fatalf("go test ./...: expected app package to pass, got:\n%s", out)
	}

	out := goCmd(t, gobin, dir, "run", "./gomapp")
	want := "12.56636\ncircle 4\n2\n6.28318\n"
	if out != want {
		t.Fatalf("go run ./gomapp = %q, want %q", out, want)
	}
}

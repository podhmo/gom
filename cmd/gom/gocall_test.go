package main

// P3-6 — Go calls Gom (spec 8.7): testdata/gocall is a nested Go
// module holding a generated Gom library plus a hand-written Go
// helper package and a Go consumer test. The Go test is the
// boundary verifier: it constructs and type-switches the generated
// ADT, passes nil/invalid values and asserts the panic contract,
// exercises the List/Go.Slice copy split, named types, interfaces,
// Result/Option, and reads back %T of values Gom boxes into `any`.
// This driver copies the fixture, runs the real gom CLI through
// check and build, then lets the real Go toolchain compile the
// module and run the consumer test end to end.

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// copyGocall copies the testdata/gocall tree into dir, skipping a
// .go file only when a same-basename .gom sibling exists — that pair
// is `gom build` output regenerated during the test; every other
// .go file (helper package, consumer test) is source and copies.
func copyGocall(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if info.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		if strings.HasSuffix(path, ".go") {
			if _, err := os.Stat(strings.TrimSuffix(path, ".go") + ".gom"); err == nil {
				return nil // generated by `gom build` during the test
			}
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

func TestEndToEnd_GoCallsGom(t *testing.T) {
	gobin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("no go toolchain on PATH")
	}
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	copyGocall(t, filepath.Join(root, "testdata", "gocall"), dir)
	if !goAtLeast(gobin, dir, 1, 27) {
		t.Skip("fixture requires go >= 1.27 (testdata/gocall/go.mod)")
	}

	// Point the committed relative replace at this worktree.
	gomodPath := filepath.Join(dir, "go.mod")
	gomod, err := os.ReadFile(gomodPath)
	if err != nil {
		t.Fatal(err)
	}
	gomod = []byte(strings.ReplaceAll(string(gomod), "=> ../..", "=> "+root))
	if err := os.WriteFile(gomodPath, gomod, 0o644); err != nil {
		t.Fatal(err)
	}

	geomDir := filepath.Join(dir, "geom")

	// gom check compiles geom as one unit — geom.gom + the .gomi.
	if code, out, errout := invoke("check", "-format", "text", geomDir); code != 0 {
		t.Fatalf("gom check: exit %d; stdout=%q stderr=%q", code, out, errout)
	}

	// gom build emits geom/geom.go next to the source.
	if code, out, errout := invoke("build", geomDir); code != 0 {
		t.Fatalf("gom build: exit %d; stdout=%q stderr=%q", code, out, errout)
	}
	if _, err := os.Stat(filepath.Join(dir, "geom", "geom.go")); err != nil {
		t.Fatalf("expected generated file geom/geom.go: %v", err)
	}

	// The Go toolchain compiles the whole module — generated geom,
	// hand-written helper, and the consumer test — then runs the
	// boundary assertions from the Go side.
	goCmd(t, gobin, dir, "build", "./...")
	if out := goCmd(t, gobin, dir, "test", "./..."); !strings.Contains(out, "ok  \texample.com/gocall/geom") && !strings.Contains(out, "ok  	example.com/gocall/geom") {
		t.Fatalf("go test ./...: expected geom package to pass, got:\n%s", out)
	}
}

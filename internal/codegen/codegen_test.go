// TestGoldenFixture diffs the whole fixture's generated output —
// main source and test source — against the golden files under
// testdata/. Every node family lands in one reviewable diff;
// regenerate with `go test ./internal/codegen -update`.
func TestGoldenFixture(t *testing.T) {
	out, err := File(buildFixture(), fixtureSrc())
	if err != nil {
		t.Fatal(err)
	}
	goldenFile(t, "fixture.golden.go", out.Source)
	goldenFile(t, "fixture_test.golden.go", out.TestSource)
}

// goldenFile compares got against testdata/name, rewriting it under
// -update. Comparison is byte-exact: gofmt output is canonical.
func goldenFile(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("missing golden %s (run `go test -update`): %v", path, err)
	}
	if string(want) != string(got) {
		t.Errorf("%s mismatch — run `go test ./internal/codegen -update` and review the diff", name)
	}
}

// TestFuncDecl asserts the small end of the output contract: a
// two-argument function, its //line mapping, and the doc header.
func TestFuncDecl(t *testing.T) {
	f := &core.File{Sp: lsp(1), Package: "shapes", PkgSp: lsp(1)}

	aB, aS := vbind("a", types.Int)
	bB, bS := vbind("b", types.Int)
	f.Decls = append(f.Decls, &core.FuncDecl{
		Sp: lsp(3), Sym: fsym("add2"),
		Fn: &core.Func{
			Sp:     lsp(3),
			Sig:    fnIII,
			Params: []*core.Bind{aB, bB},
			Body: &core.Body{Tail: &core.Binary{
				Base: core.Base{Sp: lsp(4), Typ: types.Int},
				Op:   syntax.BinAdd, X: vref(aS, types.Int), Y: vref(bS, types.Int),
			}},
		},
	})

	out, err := File(f, fakeSrc())
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by gom. DO NOT EDIT.

package shapes

//line t.gom:3
func add2(a, b int64) int64 {
//line t.gom:4
	return a + b
}
`
	if string(out.Source) != want {
		t.Errorf("generated source mismatch:\n%s", string(out.Source))
	}
	if len(out.TestSource) != 0 {
		t.Errorf("unexpected test source: %q", out.TestSource)
	}
}

// TestInvalidFile checks File rejects a validator-dirty file instead
// of generating from it (codegen.go — File validates first).
func TestInvalidFile(t *testing.T) {
	f := &core.File{Sp: lsp(1), Package: "shapes", PkgSp: lsp(1)}
	// a function whose declared arity exceeds the signature's
	// params — the validator reports the shape
	aB, _ := vbind("a", types.Int)
	f.Decls = append(f.Decls, &core.FuncDecl{
		Sp: lsp(2), Sym: fsym("bad"),
		Fn: &core.Func{
			Sp:     lsp(2),
			Sig:    fnII,
			Params: []*core.Bind{aB, aB},
			Body:   &core.Body{Tail: intLit("0")},
		},
	})
	_, err := File(f, fakeSrc())
	var iv *InvalidFileError
	if !errors.As(err, &iv) {
		t.Fatalf("File accepted an invalid Core file: %v", err)
	}
	if len(iv.Violations) == 0 {
		t.Error("InvalidFileError carries no violations")
	}
}

// TestCtorLetConversion: `let a = A` / `let b = B 1` on a local sum
// emits the ADT-interface conversion — `a := Sh(Sh_A{})` — because
// `:=` would otherwise bind the concrete variant struct and the
// later `a == b` would compare two different concrete types (which
// does not compile). The builtin Result representation emits
// constructor *calls* already typed at the declared type, so it is
// exempt.
func TestCtorLetConversion(t *testing.T) {
	shSym := tsym("Sh")
	shT := &types.Con{Name: "Sh"}
	aCt, bCt := csym("A"), csym("B")
	f := &core.File{Sp: lsp(1), Package: "shapes", PkgSp: lsp(1)}
	f.Decls = append(f.Decls, &core.TypeDecl{
		Sp: lsp(3), Sym: shSym,
		Body: &core.TSum{Sp: lsp(3), Variants: []core.TVariant{
			{Sp: lsp(3), Sym: aCt},
			{Sp: lsp(3), Sym: bCt, Fields: []core.TField{
				{Sp: lsp(3), Index: 0, Type: types.Int},
			}},
		}},
	})
	aB, aS := vbind("a", shT)
	bB, bS := vbind("b", shT)
	f.Decls = append(f.Decls, &core.FuncDecl{
		Sp: lsp(5), Sym: fsym("neq"),
		Fn: &core.Func{
			Sp:  lsp(5),
			Sig: types.Fn(types.Bool),
			Body: &core.Body{
				Lets: []*core.Let{
					{Sp: lsp(6), Name: aB, X: &core.CtorApp{
						Base: core.Base{Sp: lsp(6), Typ: shT}, Ctor: aCt, Arity: 0}},
					{Sp: lsp(7), Name: bB, X: &core.CtorApp{
						Base: core.Base{Sp: lsp(7), Typ: shT}, Ctor: bCt,
						Args: []core.Atom{intLit("1")}, Arity: 1}},
				},
				Tail: &core.Equal{
					Base: core.Base{Sp: lsp(8), Typ: types.Bool},
					X:    vref(aS, shT), Y: vref(bS, shT),
					How: &core.EqPlan{Kind: core.EqNative},
				},
			},
		},
	})
	out, err := File(f, fakeSrc())
	if err != nil {
		t.Fatal(err)
	}
	src := string(out.Source)
	for _, want := range []string{
		"a := Sh(Sh_A{})",
		"b := Sh(Sh_B{V0: 1})",
		"return a == b",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated source lacks %q:\n%s", want, src)
		}
	}
}

// TestEqMapDecl: a Go.Map comparator emits the key-set/value loop,
// and — like every comparator — carries its //line only on the
// declaration, never on the generated body statements.
func TestEqMapDecl(t *testing.T) {
	mapT := &types.Con{Qual: "Go", Name: "Map",
		Args: []types.Type{types.String, types.Int}}
	f := &core.File{Sp: lsp(1), Package: "shapes", PkgSp: lsp(1)}
	f.EqDecls = []*core.EqDecl{{
		Sp:  lsp(3),
		Sym: &resolve.Symbol{Name: "gomEq1_deadbeef", Kind: resolve.KindFunc},
		Typ: mapT,
		Plan: &core.EqPlan{Kind: core.EqMap,
			Elem: &core.EqPlan{Kind: core.EqNative}},
	}}
	out, err := File(f, fakeSrc())
	if err != nil {
		t.Fatal(err)
	}
	src := string(out.Source)
	for _, want := range []string{
		"func gomEq1Deadbeef(a, b map[string]int64) bool",
		"for k, av := range a",
		"bv, ok := b[k]",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated comparator lacks %q:\n%s", want, src)
		}
	}
	if n := strings.Count(src, "//line"); n != 1 {
		t.Errorf("comparator emitted %d //line directives, want the declaration's one:\n%s", n, src)
	}
}

// fakeSrc is the .gom source text the fixture spans index into —
// 40-byte lines so tsp()'s `n*10` offsets map to line n/4-ish.
func fakeSrc() []byte {
	var b []byte
	for i := 0; i < 200; i++ {
		b = append(b, []byte(fmt.Sprintf("// line %03d                      \n", i))...)
	}
	return b
}

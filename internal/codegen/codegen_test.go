var update = flag.Bool("update", false, "rewrite the testdata golden files")

// testsp returns a span pointing into the fake source line table the
// tests build — only validity matters, the file name is the .gom
// name the //line directives cite. The counter is reset at the top
// of buildFixture so golden //line numbers are stable across test
// reruns (`go test -count=N` rebuilds the fixture each time).
var tspn int

func tsp() diag.Span {
	tspn++
	return diag.SpanIn("t.gom", tspn*10, tspn*10+5)
}

// lsp returns a span on a fixed source line of fakeSrc — for tests
// that assert exact //line directives, independent of the shared
// tsp() counter. fakeSrc's lines are 40 bytes.
func lsp(line int) diag.Span {
	return diag.SpanIn("t.gom", (line-1)*40, (line-1)*40+5)
}

func vsym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindVar}
}
func fsym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindFunc}
}
func csym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindCtor}
}
func tsym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindType}
}
func fdsym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindField}
}
func gsym(name, pkg string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindFunc, IsGo: true, Package: pkg}
}
func bsym(name string) *resolve.Symbol {
	return &resolve.Symbol{Name: name, Kind: resolve.KindBuiltin}
}

func bind(s *resolve.Symbol, t types.Type) *core.Bind {
	return &core.Bind{Sp: tsp(), Sym: s, Typ: t}
}
func vbind(name string, t types.Type) (*core.Bind, *resolve.Symbol) {
	s := vsym(name)
	return bind(s, t), s
}
func vref(s *resolve.Symbol, t types.Type) *core.Var {
	return &core.Var{Base: core.Base{Sp: tsp(), Typ: t}, Sym: s}
}
func intLit(text string) *core.Lit {
	return &core.Lit{Base: core.Base{Sp: tsp(), Typ: types.Int}, Kind: syntax.LitInt, Text: text}
}
func unitLit() *core.Lit {
	return &core.Lit{Base: core.Base{Sp: tsp(), Typ: types.Unit}, Kind: syntax.LitUnit, Text: "()"}
}

